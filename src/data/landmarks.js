export const categoryOrder = ["全部", "教学", "生活", "运动", "人文"];

export function addMappedBuildings(buildings) {
  const existing = new Set(landmarks.map((p) => p.id));
  for (const b of buildings) {
    const name = b.name.trim();
    if (
      existing.has(b.id) ||
      name.length < 2 ||
      !/[\u4e00-\u9fff]/.test(name) ||
      /^[\dA-H-]+$/.test(name) ||
      [
        "南",
        "东栋",
        "西栋",
        "收发室",
        "能源管理办",
        "岳麓区交警大队四中队牌楼路岗亭",
        "改建村",
      ].includes(name)
    )
      continue;
    const category = /体育|游泳/.test(name)
      ? "运动"
      : /食堂|宿舍|公寓|舍|斋/.test(name)
        ? "生活"
        : b.style === "heritage" || /亭|书院|博物馆|礼堂/.test(name)
          ? "人文"
          : "教学";
    const interior =
      category === "运动"
        ? "gym"
        : category === "生活"
          ? /食堂/.test(name)
            ? "canteen"
            : "dorm"
          : category === "人文"
            ? "hall"
            : "classroom";
    landmarks.push({
      id: b.id,
      name,
      category,
      subtitle: "校园地图标注建筑",
      description:
        "位置和平面轮廓参照 OpenStreetMap。楼高、外立面与室内空间为艺术化示意，具体情况请以实地为准。",
      icon:
        category === "运动"
          ? "◉"
          : category === "生活"
            ? "▦"
            : category === "人文"
              ? "⌂"
              : "▤",
      interior,
      source: "https://www.openstreetmap.org/copyright",
    });
    existing.add(b.id);
  }
}
